//! Original numeric fixtures observed through the external 4.3 public API.
//! The 79-case matrix and independent 24-case holdout establish X-to-Rotate;
//! exact unbiased -180 uses the negative turn, unlike legacy identity Rotate.
use crate::*;
use peachy_document::*;

fn bone(name: &str, parent: usize, setup: Transform, length: f32) -> Bone {
    Bone {
        name: name.into(),
        parent: Some(parent),
        setup,
        length,
        inherit: Inherit::Normal,
    }
}

fn rig() -> Document {
    let mut doc = Document::new("Original cross mapping".into(), 60).unwrap();
    doc.bones.extend([
        bone(
            "source parent",
            0,
            Transform {
                y: 120.,
                ..Default::default()
            },
            0.,
        ),
        bone(
            "driver",
            1,
            Transform {
                x: 20.,
                ..Default::default()
            },
            60.,
        ),
        bone(
            "follower parent",
            0,
            Transform {
                y: -100.,
                ..Default::default()
            },
            0.,
        ),
        bone(
            "follower",
            3,
            Transform {
                rotation: 30.,
                ..Default::default()
            },
            120.,
        ),
        bone(
            "tip",
            4,
            Transform {
                x: 120.,
                ..Default::default()
            },
            20.,
        ),
    ]);
    doc.constraints
        .push(Constraint::Transform(TransformConstraint {
            name: "X to Rotate".into(),
            bones: vec![4],
            source: 2,
            offsets: TransformValues::default(),
            mix: TransformValues {
                rotate: 1.,
                ..Default::default()
            },
            mappings: vec![TransformMapping {
                from: TransformProperty::X,
                offset: 0.,
                to: vec![TransformTarget::identity(TransformProperty::Rotate)],
            }],
            local_source: false,
            local_target: false,
            additive: false,
            clamp: false,
        }));
    doc.animations.push(Animation::new("calibration", vec![]));
    doc.validate().unwrap();
    doc
}

fn constraint(doc: &mut Document) -> &mut TransformConstraint {
    let Constraint::Transform(value) = &mut doc.constraints[0] else {
        panic!()
    };
    value
}

fn frame(matrix: Affine) -> [f64; 6] {
    [matrix.a, matrix.b, matrix.c, matrix.d, matrix.x, matrix.y].map(f64::from)
}

fn near(actual: f64, expected: f64, tolerance: f64) {
    assert!(
        (actual - expected).abs() <= tolerance,
        "{actual} vs {expected}"
    );
}

