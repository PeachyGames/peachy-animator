#[test]
fn cross_mapping_halfturn_ties_and_large_turns_use_the_observed_single_correction() {
    for (x, tip) in [
        (180., [0., 120.]),
        (-180., [0., -120.]),
        (540., [0., 120.]),
        (-540., [0., -120.]),
        (720., [-120., 0.]),
        (-720., [-120., 0.]),
        (179.99998, [0., 120.]),
        (180.00002, [0., -120.]),
        (-179.99998, [0., -120.]),
        (-180.00002, [0., 120.]),
    ] {
        let mut doc = rig();
        doc.bones[1].setup.y = 0.;
        doc.bones[2].setup.x = x;
        doc.bones[3].setup.y = 0.;
        doc.bones[4].setup.rotation = 0.;
        constraint(&mut doc).mix.rotate = 0.5;
        let pose = checked_evaluate_pose(&doc, None, 0.).unwrap();
        near(f64::from(pose.world()[5].x), tip[0], 0.001);
        near(f64::from(pose.world()[5].y), tip[1], 0.001);
    }
}

#[test]
fn cross_mapping_large_f32_payload_converts_to_radians_before_mixing() {
    // Identical native f32 source/mix values were exported to the external
    // runtime. Multiplying mix before the degree conversion moves this tip
    // by over 9 units; these original public observations distinguish them.
    let mut doc = rig();
    doc.bones[1].setup.y = 0.;
    doc.bones[2].setup.x = 1e38;
    doc.bones[3].setup.y = 0.;
    doc.bones[4].setup.rotation = 0.;
    constraint(&mut doc).mix.rotate = 0.35;
    let pose = checked_evaluate_pose(&doc, None, 0.).unwrap();
    near(f64::from(pose.world()[4].a), -0.7948060366573679, 0.00001);
    near(f64::from(pose.world()[4].c), -0.6068635465184959, 0.00001);
    near(f64::from(pose.world()[5].x), -95.37672439888415, 0.001);
    near(f64::from(pose.world()[5].y), -72.8236255822195, 0.001);
}

#[test]
fn cross_mapping_refuses_measured_consumer_boundary_without_changing_unbiased_native_turn() {
    let mut doc = rig();
    doc.bones[2].setup.x = -180.;
    doc.bones[4].setup.rotation = 0.;
    constraint(&mut doc).mix.rotate = 0.5;
    let locals = doc.bones.iter().map(|bone| bone.setup).collect::<Vec<_>>();
    let inherits = vec![Inherit::Normal; doc.bones.len()];
    let narrow = world_pose_with(&doc, &locals, &inherits);
    let diagnostic = crate::pose::world_pose_wide(&doc, &locals, &inherits).unwrap();
    assert_eq!(narrow[2].x, -180.);
    near(diagnostic[2][4], -180.0000027846124, 0.0000000001);
    let error = checked_evaluate_pose(&doc, None, 0.).unwrap_err();
    assert!(error.contains("X to Rotate") && error.contains("follower"));
    assert!(error.contains("native/editor and runtime") && error.contains("precision boundary"));
    // The paired installed control with no source-parent Y bias points down.
    doc.bones[1].setup.y = 0.;
    doc.bones[3].setup.y = 0.;
    let unbiased = checked_evaluate_pose(&doc, None, 0.).unwrap();
    near(f64::from(unbiased.world()[5].y), -120., 0.001);
    // Zero Mix bypasses the diagnostic exactly, retaining the authored pose.
    doc.bones[1].setup.y = 120.;
    constraint(&mut doc).mix.rotate = 0.;
    let inactive = checked_evaluate_pose(&doc, None, 0.).unwrap();
    assert_eq!(inactive.applied_locals(), inactive.authored_locals());
    // The existing same-property X solver keeps its established f32 arithmetic.
    constraint(&mut doc).mappings[0].to[0].property = TransformProperty::X;
    constraint(&mut doc).mix.x = 0.5;
    assert!(checked_evaluate_pose(&doc, None, 0.).is_ok());
}

#[test]
fn cross_mapping_diagnostic_checks_follower_angle_as_well_as_source_point() {
    let mut doc = rig();
    doc.bones[1].setup.y = 0.;
    doc.bones[2].setup.x = -180.;
    doc.bones[3].setup.y = 0.;
    doc.bones[3].setup.rotation = 30.;
    doc.bones[4].setup.rotation = -30.;
    constraint(&mut doc).mix.rotate = 0.5;
    let locals = doc.bones.iter().map(|bone| bone.setup).collect::<Vec<_>>();
    let inherits = vec![Inherit::Normal; doc.bones.len()];
    let narrow = world_pose_with(&doc, &locals, &inherits);
    let diagnostic = crate::pose::world_pose_wide(&doc, &locals, &inherits).unwrap();
    assert_eq!(narrow[4].c, 0.);
    assert!(diagnostic[4][2] > 0.);
    assert!(
        checked_evaluate_pose(&doc, None, 0.)
            .unwrap_err()
            .contains("precision boundary")
    );
    assert!(crate::pose::world_pose_wide(&doc, &[], &inherits).is_err());
    assert!(crate::pose::world_pose_wide(&doc, &locals, &[]).is_err());
}

#[test]
fn cross_mapping_checks_final_f32_angle_after_clamping_and_zero_mix_is_exact() {
    let mut doc = rig();
    doc.bones[2].setup.x = f32::MAX / 4.;
    constraint(&mut doc).mappings[0].to[0].scale = 16.;
    assert!(
        checked_evaluate_pose(&doc, None, 0.)
            .unwrap_err()
            .contains("mapped angle is outside the finite f32 range")
    );
    let c = constraint(&mut doc);
    c.clamp = true;
    c.mappings[0].to[0].offset = -90.;
    c.mappings[0].to[0].max = 90.;
    let clamped = checked_evaluate_pose(&doc, None, 0.).unwrap();
    near(f64::from(clamped.world()[4].a), 0., 0.00001);
    near(f64::from(clamped.world()[4].c), 1., 0.00001);
    constraint(&mut doc).clamp = false;
    constraint(&mut doc).mix.rotate = 0.;
    let inactive = checked_evaluate_pose(&doc, None, 0.).unwrap();
    assert_eq!(inactive.applied_locals(), inactive.authored_locals());
    let expected = world_pose(&doc, inactive.authored_locals());
    assert_eq!(
        inactive
            .world()
            .iter()
            .copied()
            .map(frame)
            .collect::<Vec<_>>(),
        expected.into_iter().map(frame).collect::<Vec<_>>()
    );
}

#[test]
fn cross_mapping_refuses_ambiguous_writers_other_mappings_and_existing_unsafe_domains() {
    let original = rig();
    for from in [
        TransformProperty::Y,
        TransformProperty::ScaleX,
        TransformProperty::ShearY,
    ] {
        let mut doc = original.clone();
        constraint(&mut doc).mappings[0].from = from;
        doc.validate().unwrap();
        assert!(
            checked_evaluate_pose(&doc, None, 0.)
                .unwrap_err()
                .contains("only X/Y mappings")
        );
    }
    let mut multi = original.clone();
    constraint(&mut multi).mappings[0]
        .to
        .push(TransformTarget::identity(TransformProperty::X));
    assert!(checked_evaluate_pose(&multi, None, 0.).is_err());
    let mut duplicate = original.clone();
    constraint(&mut duplicate).mappings.push(TransformMapping {
        from: TransformProperty::Rotate,
        offset: 0.,
        to: vec![TransformTarget::identity(TransformProperty::Rotate)],
    });
    duplicate.validate().unwrap();
    assert!(
        checked_evaluate_pose(&duplicate, None, 0.)
            .unwrap_err()
            .contains("exactly one writer")
    );
    for mode in 0..6 {
        let mut doc = original.clone();
        let reason = match mode {
            0 => {
                constraint(&mut doc).local_source = true;
                "local and additive"
            }
            1 => {
                constraint(&mut doc).local_target = true;
                "local and additive"
            }
            2 => {
                constraint(&mut doc).additive = true;
                "local and additive"
            }
            3 => {
                doc.bones[4].inherit = Inherit::NoScale;
                "must inherit normally"
            }
            4 => {
                constraint(&mut doc).source = 5;
                "inside constrained bone"
            }
            _ => {
                doc.bones[3].setup.scale_x = 0.;
                "singular parent"
            }
        };
        assert!(
            checked_evaluate_pose(&doc, None, 0.)
                .unwrap_err()
                .contains(reason)
        );
    }
}

#[test]
fn cross_mapping_samples_pending_source_and_raw_constraint_edits_keep_atomic_history() {
    let mut doc = rig();
    doc.animations[0].tracks.push(Track {
        bone: 2,
        property: Property::X,
        keys: vec![
            Keyframe {
                time: 0.,
                value: 0.,
                curve: Curve::Linear,
            },
            Keyframe {
                time: 1.,
                value: 80.,
                curve: Curve::Linear,
            },
        ],
    });
    let target = EditTarget::Animate {
        animation: 0,
        time: 0.5,
    };
    let mut session = Session::new(doc.clone()).unwrap();
    let sampled = session.evaluated_pose(target).unwrap();
    near(f64::from(sampled.world()[4].a), 0.5, 0.00001);
    let mut pending_transform = sampled.authored_locals()[2];
    pending_transform.x = 73.25;
    session
        .edit_pose(2, target, pending_transform, &[Property::X], false)
        .unwrap();
    let pending = session.pose_edits().clone();
    let mut changed = constraint(&mut doc).clone();
    changed.mappings[0].to[0].offset = 15.;
    session
        .dispatch(Command::SetTransformConstraint {
            constraint: 0,
            value: changed,
        })
        .unwrap();
    let edited = session.document().clone();
    assert_eq!(session.pose_edits(), &pending);
    assert_eq!(session.document().animations, doc.animations);
    session.undo();
    assert_eq!(session.document(), &doc);
    assert_eq!(session.pose_edits(), &pending);
    let mut invalid = constraint(&mut doc).clone();
    invalid.mappings[0].to[0].scale = f32::INFINITY;
    assert!(
        session
            .dispatch(Command::Batch {
                commands: vec![
                    Command::RenameAnimation {
                        animation: 0,
                        name: "rollback".into()
                    },
                    Command::SetTransformConstraint {
                        constraint: 0,
                        value: invalid
                    },
                ]
            })
            .is_err()
    );
    assert_eq!(session.document(), &doc);
    assert_eq!(session.pose_edits(), &pending);
    assert!(session.can_redo());
    session.redo();
    assert_eq!(session.document(), &edited);
    assert_eq!(session.pose_edits(), &pending);
    // Raw Add/Set still store complete model-valid data; evaluation refuses it.
    let mut unsupported = constraint(&mut doc).clone();
    unsupported.mappings[0].from = TransformProperty::Y;
    session
        .dispatch(Command::SetTransformConstraint {
            constraint: 0,
            value: unsupported,
        })
        .unwrap();
    assert!(session.evaluated_pose(target).is_err());
}

#[test]
fn cross_mapping_uses_preceding_applied_source_for_multiple_disjoint_followers() {
    let mut doc = rig();
    doc.bones.push(bone(
        "other follower",
        3,
        Transform {
            x: 13.25,
            rotation: -118.,
            scale_x: -0.7,
            scale_y: 1.2,
            shear_y: 17.,
            ..Default::default()
        },
        71.,
    ));
    doc.bones.push(bone(
        "prior source",
        0,
        Transform {
            x: -47.25,
            y: 55.5,
            ..Default::default()
        },
        0.,
    ));
    constraint(&mut doc).bones.push(6);
    let prior = TransformConstraint {
        name: "prior translation".into(),
        bones: vec![2],
        source: 7,
        offsets: TransformValues::default(),
        mix: TransformValues {
            x: 1.,
            ..Default::default()
        },
        mappings: vec![TransformMapping {
            from: TransformProperty::X,
            offset: 0.,
            to: vec![TransformTarget::identity(TransformProperty::X)],
        }],
        local_source: false,
        local_target: false,
        additive: false,
        clamp: false,
    };
    doc.constraints.insert(0, Constraint::Transform(prior));
    let pose = checked_evaluate_pose(&doc, None, 0.).unwrap();
    for index in [4, 6] {
        let actual = f64::from(pose.world()[index].c)
            .atan2(f64::from(pose.world()[index].a))
            .to_degrees();
        near(actual, -47.25, 0.0001);
    }
    let tip = pose.world()[4].point(120., 0.);
    near(f64::from(pose.world()[5].x), f64::from(tip[0]), 0.001);
    near(f64::from(pose.world()[5].y), f64::from(tip[1]), 0.001);
}
